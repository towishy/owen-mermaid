export const catalogs: Record<Locale, Catalog> = { en, ko };

export function normalizeLocale(value: unknown): Locale {
  return value === "ko" ? "ko" : DEFAULT_LOCALE;
}

export function normalizeLocalePreference(value: unknown): LocalePreference {
  return value === "en" || value === "ko" ? value : "auto";
}

export function resolveLocale(preference: LocalePreference, obsidianLocale: unknown): Locale {
  if (preference === "en" || preference === "ko") return preference;
  return typeof obsidianLocale === "string" && /^ko(?:[-_]|$)/i.test(obsidianLocale) ? "ko" : DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: TranslationKey, variables: Record<string, string | number> = {}): string {
  const template = catalogs[locale]?.[key] ?? catalogs[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match,
  );
}

export type Translator = (key: TranslationKey, variables?: Record<string, string | number>) => string;

export function createTranslator(locale: Locale): Translator {
  return (key, variables) => translate(locale, key, variables);
}